function ErrorComponent({ error, reset }: ErrorComponentProps) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-[60vh] items-center justify-center px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold">حدث خطأ غير متوقع</h1>
        <p className="text-muted-foreground mt-2 text-sm">
          لم يتم تحميل الصفحة. جرّب التحديث أو العودة للرئيسية.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="gradient-primary-bg text-primary-foreground inline-flex items-center justify-center rounded-md px-4 py-2 text-sm font-medium"
          >
            إعادة المحاولة
          </button>
          <a
            href="/"
            className="border-input hover:bg-accent inline-flex items-center justify-center rounded-md border px-4 py-2 text-sm font-medium"
          >
            العودة للرئيسية
          </a>
        </div>
      </div>
    </div>
  );
}

